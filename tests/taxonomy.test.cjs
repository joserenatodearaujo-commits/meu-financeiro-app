'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..');
const categories=['Moradia','Alimentação','Transporte','Saúde','Educação','Lazer','Família','Financeiro','Outros'];
const microbes={Moradia:['Aluguel','Financiamento','Energia','Água','Internet','Condomínio'],Alimentação:['Supermercado','Restaurante','Delivery'],Transporte:['Combustível','Manutenção','Seguro','IPVA'],Saúde:['Consultas','Farmácia','Plano de saúde'],Educação:['Escola','Cursos','Material'],Lazer:['Passeios','Viagens','Assinaturas'],Família:['Crianças','Vestuário','Diversos'],Financeiro:['Juros','Tarifas'],Outros:['Diversos']};
const context=vm.createContext({categories,microbes});vm.runInContext(fs.readFileSync(path.join(root,'js/finance/taxonomy.js'),'utf8'),context);
const R=vm.runInContext('TaxonomyRules',context);let cases=0;
function ok(condition,label){assert(condition,label);cases++}
function throws(fn,pattern,label){assert.throws(fn,pattern,label);cases++}
let t=R.defaults();
ok(t.entries.length===9,'9 categorias padrão');
ok(t.entries.reduce((n,x)=>n+x.subcategories.length,0)===28,'28 subcategorias padrão');
t=R.addCategory(t,' Pets ');
ok(t.entries.some(x=>x.name==='Pets'),'adiciona categoria');
throws(()=>R.addCategory(t,'PETS'),/já existe/,'não duplica categoria');
t=R.addSub(t,'Pets','Ração');
ok(R.find(t,'Pets').subcategories.includes('Ração'),'inclui subcategoria');
throws(()=>R.addSub(t,'Pets','ração'),/já existe/,'não duplica subcategoria sem acento');
t=R.renameSub(t,'Pets','Ração','Ração e petiscos',{transactions:[]});
ok(R.find(t,'Pets').subcategories.includes('Ração e petiscos'),'renomeia subcategoria livre');
throws(()=>R.renameSub(t,'Pets','Ração e petiscos','Medicamentos',{transactions:[{macro:'Pets',micro:'Ração e petiscos'}]}),/vinculados/,'bloqueia edição com lançamento');
throws(()=>R.deleteSub(t,'Pets','Ração e petiscos',{transactions:[{macro:'Pets',micro:'Ração e petiscos'}]}),/vinculados/,'bloqueia exclusão com lançamento');
t=R.renameCategory(t,'Pets','Animais',{transactions:[],goals:[]});
ok(!!R.find(t,'Animais'),'renomeia categoria livre');
throws(()=>R.deleteCategory(t,'Animais',{transactions:[],goals:[{macro:'Animais'}]}),/vinculados/,'protege metas');
throws(()=>R.renameCategory(t,'Outros','Nova categoria',{transactions:[],goals:[]}),/Outros/,'preserva categoria fallback');
t=R.deleteSub(t,'Animais','Ração e petiscos',{transactions:[]});
ok(!R.find(t,'Animais').subcategories.includes('Ração e petiscos'),'exclui subcategoria sem uso');
t=R.deleteCategory(t,'Animais',{transactions:[],goals:[]});
ok(!R.find(t,'Animais'),'exclui categoria sem uso');
throws(()=>R.addCategory(t,'a'),/entre 2 e 60/,'validação mínima');
throws(()=>R.addCategory(t,'<script>alert(1)</script>'),/caracteres inválidos/,'não aceita markup');
const old={transactions:[{macro:'Transporte',micro:'Pedágio'},{macro:'Investimentos',micro:'Ações'}],goals:[{macro:'Categoria antiga'}]};
context.financial=old;vm.runInContext('ensureTaxonomy(financial)',context);
ok(old.taxonomy.entries.some(e=>e.name==='Investimentos'&&e.subcategories.includes('Ações')),'migra classificação legada sem alterar transações');
ok(R.find(old.taxonomy,'Transporte').subcategories.includes('Pedágio'),'importa subcategoria histórica');
ok(!!R.find(old.taxonomy,'Categoria antiga'),'preserva categoria ligada à meta');
ok(old.transactions[0].micro==='Pedágio','histórico intacto');
const current=old.taxonomy;vm.runInContext('ensureTaxonomy(financial)',context);
ok(old.taxonomy===current,'migração idempotente');
console.log('PASS '+cases+' cadastro de categorias, subcategorias e legado');
