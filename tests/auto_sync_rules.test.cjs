'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'../js/core/auto-sync.js'),'utf8');
const helpers=src.slice(src.indexOf('function autoEqual('),src.indexOf('async function autoSetLocalOfficial('));
const ctx=vm.createContext({});vm.runInContext(helpers,ctx);
const merge=vm.runInContext('autoThreeWay',ctx);
const test=(name,expected,actual)=>assert.deepEqual(JSON.parse(JSON.stringify(actual)),expected,name);
const tx=(id,amount)=>({id,amount,type:'expense'});
const base={transactions:[tx('x',10)],accounts:[{id:'a',name:'Bank'}],goals:[],transfers:[],invoicePayments:[],importCheckpoints:[],taxonomy:{Moradia:['Aluguel']},version:1};
let local=structuredClone(base),server=structuredClone(base);
local.transactions.push(tx('android',12));server.transactions.push(tx('desktop',13));
let result=merge(base,local,server);
test('disjoint inserts converge',[],result.conflicts);
test('all unique transaction IDs',["x","android","desktop"],result.result.transactions.map(x=>x.id));
local=structuredClone(base);server=structuredClone(base);
local.transactions[0].amount=99;server.transactions.push(tx('extra',25));
result=merge(base,local,server);
test('remote insert + local edit preserved',[],result.conflicts);
test('local edit preserved',99,result.result.transactions.find(t=>t.id==='x').amount);
local=structuredClone(base);server=structuredClone(base);
local.transactions[0].amount=20;server.transactions[0].amount=30;
result=merge(base,local,server);
test('conflict same ID preserved for resolution',['transactions:x'],result.conflicts);
local=structuredClone(base);server=structuredClone(base);
local.transactions=[];server.transactions.push(tx('another',5));
result=merge(base,local,server);
test('deletion is not resurrected',["another"],result.result.transactions.map(x=>x.id));
local=structuredClone(base);server=structuredClone(base);
local.taxonomy.Moradia.push('Internet');server.transactions.push(tx('y',18));
result=merge(base,local,server);
test('taxonomy and transactions coexist',[],result.conflicts);
test('taxonomy not discarded',['Aluguel','Internet'],result.result.taxonomy.Moradia);
local=structuredClone(base);server=structuredClone(base);
local.accounts.push({id:'b',name:'Second'});server.accounts[0].name='Edited bank';
result=merge(base,local,server);
test('same collection disjoint edits merge',[],result.conflicts);
test('account names',["Edited bank","Second"],result.result.accounts.map(a=>a.name));
console.log('PASS 8 tests: merge disjoint IDs, deletion, categories, and same-record conflicts');
